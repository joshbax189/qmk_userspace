// send arrow strings on keyoverride
static bool send_single_arrow(bool activated, void *context) {
    if (activated) {
        del_mods(MOD_MASK_SHIFT);
        SEND_STRING("->");
    }
    return false;
}

static bool send_double_arrow(bool activated, void *context) {
    if (activated) {
        del_mods(MOD_MASK_SHIFT);
        SEND_STRING("=>");
    }
    return false;
}

// overrides: shifted - and = on _SYN layer
const key_override_t single_arrow_override = {
    .trigger_mods = MOD_MASK_SHIFT,
    .trigger = KC_MINS,
    .layers = (1 << _SYN), // layer bitmask - use on the _SYN layer
    .custom_action = send_single_arrow,
    .replacement = KC_NO,
};

const key_override_t double_arrow_override = {
    .trigger_mods = MOD_MASK_SHIFT,
    .trigger = KC_EQL,
    .layers = (1 << _SYN), // layer bitmask - use on the _SYN layer
    .custom_action = send_double_arrow,
    .replacement = KC_NO,
};

const key_override_t *key_overrides[] = {
    &single_arrow_override,
    &double_arrow_override,
};

